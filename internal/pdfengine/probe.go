// Package pdfengine provides native text selection and sanitized PDF redaction.
// TrialRedact is an unsafe comparison helper; application exports must use
// RedactAndSanitize.
package pdfengine

/*
#cgo CFLAGS: -I${SRCDIR}/include
#include "bridge.h"
#include <stdlib.h>
*/
import "C"

import (
	"errors"
	"fmt"
	"math"
	"unsafe"

	// Supply the platform-specific archives through the existing dependency.
	_ "github.com/gen2brain/go-fitz"
)

type Point struct{ X, Y float64 }
type Quad struct{ UL, UR, LL, LR Point }
type Glyph struct {
	Rune   rune
	Line   int
	Quad   Quad
	Origin Point // Normalized baseline origin, independent of font ascenders.
}
type Layout struct {
	Width, Height float64
	Glyphs        []Glyph
}
type Region struct {
	Page int
	Quad Quad
}

// TextLayout extracts glyph geometry in normalized visible page coordinates.
func TextLayout(data []byte, page int) (Layout, error) {
	if len(data) == 0 || page < 0 || page > math.MaxInt32 {
		return Layout{}, errors.New("pdfengine: empty PDF or invalid page")
	}
	input := C.CBytes(data)
	defer C.free(input)
	var result C.pv_result
	defer C.pv_free_result(&result)
	C.pv_layout((*C.uchar)(input), C.size_t(len(data)), C.int(page), &result)
	if err := resultError(&result); err != nil {
		return Layout{}, err
	}
	layout := Layout{Width: float64(result.width), Height: float64(result.height)}
	for _, glyph := range unsafe.Slice(result.glyphs, int(result.glyph_count)) {
		layout.Glyphs = append(layout.Glyphs, Glyph{Rune: rune(glyph.codepoint), Line: int(glyph.line), Quad: goQuad(glyph.quad), Origin: Point{X: float64(glyph.origin.x), Y: float64(glyph.origin.y)}})
	}
	return layout, nil
}

// TrialRedact applies native redactions and a complete nonincremental rewrite.
// It does not sanitize retained resources and must never be used by exports.
func TrialRedact(data []byte, regions []Region) ([]byte, error) {
	return apply(data, regions, 0)
}

// RedactAndSanitize removes selected content, strips ancillary data and rewrites
// every use of an affected image. Unsupported structures return no output.
func RedactAndSanitize(data []byte, regions []Region) ([]byte, error) {
	return apply(data, regions, 1)
}

func apply(data []byte, regions []Region, mode int) ([]byte, error) {
	if len(data) == 0 || len(regions) == 0 {
		return nil, errors.New("pdfengine: PDF and redaction regions are required")
	}
	native := make([]C.pv_region, len(regions))
	for i, region := range regions {
		if region.Page < 0 || region.Page > math.MaxInt32 {
			return nil, errors.New("pdfengine: invalid redaction page")
		}
		if !region.Quad.Valid() {
			return nil, errors.New("pdfengine: invalid redaction quadrilateral")
		}
		for _, point := range []Point{region.Quad.UL, region.Quad.UR, region.Quad.LL, region.Quad.LR} {
			if math.IsNaN(point.X) || math.IsNaN(point.Y) || math.IsInf(point.X, 0) || math.IsInf(point.Y, 0) || point.X < 0 || point.X > 1 || point.Y < 0 || point.Y > 1 {
				return nil, errors.New("pdfengine: invalid normalized redaction geometry")
			}
		}
		native[i] = C.pv_region{page: C.int(region.Page), quad: cQuad(region.Quad)}
	}
	input := C.CBytes(data)
	defer C.free(input)
	var result C.pv_result
	defer C.pv_free_result(&result)
	if mode == 2 {
		C.pv_redact_composed((*C.uchar)(input), C.size_t(len(data)), &native[0], C.size_t(len(native)), &result)
	} else if mode == 1 {
		C.pv_redact((*C.uchar)(input), C.size_t(len(data)), &native[0], C.size_t(len(native)), &result)
	} else {
		C.pv_trial_redact((*C.uchar)(input), C.size_t(len(data)), &native[0], C.size_t(len(native)), &result)
	}
	if err := resultError(&result); err != nil {
		return nil, err
	}
	if uint64(result.length) > math.MaxInt32 {
		return nil, errors.New("pdfengine: redaction result exceeds supported size")
	}
	return C.GoBytes(unsafe.Pointer(result.bytes), C.int(result.length)), nil
}

func resultError(result *C.pv_result) error {
	if result.error[0] == 0 {
		return nil
	}
	return fmt.Errorf("pdfengine: %s", C.GoString(&result.error[0]))
}
func goPoint(p C.pv_point) Point { return Point{float64(p.x), float64(p.y)} }
func goQuad(q C.pv_quad) Quad {
	return Quad{goPoint(q.ul), goPoint(q.ur), goPoint(q.ll), goPoint(q.lr)}
}
func cPoint(p Point) C.pv_point { return C.pv_point{x: C.float(p.X), y: C.float(p.Y)} }
func cQuad(q Quad) C.pv_quad {
	return C.pv_quad{ul: cPoint(q.UL), ur: cPoint(q.UR), ll: cPoint(q.LL), lr: cPoint(q.LR)}
}

// RedactComposedPDF validates the original sources before flattening the optional
// layer wrappers generated by Proview's overlay writer. Never pass arbitrary
// PDFs as composed data; it must contain only these sources and app overlays.
func RedactComposedPDF(data []byte, regions []Region, sources [][]byte) ([]byte, error) {
	if len(sources) == 0 {
		return nil, errors.New("pdfengine: original sources required")
	}
	for _, source := range sources {
		if err := checkSource(source); err != nil {
			return nil, err
		}
	}
	return apply(data, regions, 2)
}
func checkSource(data []byte) error {
	if len(data) == 0 {
		return errors.New("pdfengine: empty source")
	}
	input := C.CBytes(data)
	defer C.free(input)
	var result C.pv_result
	defer C.pv_free_result(&result)
	C.pv_check_source((*C.uchar)(input), C.size_t(len(data)), &result)
	return resultError(&result)
}
